const getCountryNameCandidates = (name) => {
  const normalizedName = normalizeNationalityText(name);
  const compactName = normalizedName.replace(/\s+/g, "");
  const candidates = [normalizedName, compactName];

  if (normalizedName.endsWith("ia")) {
    candidates.push(`${normalizedName.slice(0, -2)}ian`);
  }

  if (normalizedName.endsWith("a")) {
    candidates.push(`${normalizedName.slice(0, -1)}an`);
  }

  if (normalizedName.endsWith("na")) {
    candidates.push(`${normalizedName.slice(0, -2)}nean`);
  }

  if (normalizedName.endsWith("land")) {
    candidates.push(`${normalizedName.slice(0, -4)}ish`);
  }

  return candidates;
};

export const getFlagIconCode = (iso) => {
  const normalizedIso = String(iso || "").toUpperCase();

  if (!normalizedIso) return "";
  return normalizedIso.replace(/-/g, "_");
};

export const CountryFlagIcon = ({ code, title, className }) => {
  const iconCode = getFlagIconCode(code);
  const FlagComponent = FlagIcons[iconCode];

  if (!FlagComponent) return null;

  return <FlagComponent title={title || iconCode} className={className} />;
};

export const getNationalityCountryCode = (option) => {
  if (!option) return "";

  if (typeof option !== "string") {
    return option.iso || "";
  }

  const optionLabel = normalizeNationalityText(option);
  const aliasIso = nationalityAliasToIso[optionLabel];

  if (aliasIso) return aliasIso;

  const match = NationalityList.find((item) => {
    const labels = [
      item.name,
      item.nationality,
      ...getCountryNameCandidates(item.name),
    ].map(normalizeNationalityText);

    return labels.includes(optionLabel);
  });

  return match?.iso || "";
};

